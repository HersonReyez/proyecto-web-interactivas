import { test, expect } from '@playwright/test'

test('visitor placeholder, responsive layout and protected routes', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Tu pasión merece/ })).toBeVisible()
  await expect(page.getByText('Catálogo en preparación')).toBeVisible()
  await page.screenshot({ path: 'test-results/visitor-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('link', { name: 'Crear cuenta' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/visitor-mobile.png', fullPage: true })
  await page.goto('/admin/usuarios')
  await expect(page).toHaveURL(/\/login$/)
})

test('register, persist session, edit profile, change password and logout', async ({ page }) => {
  await page.goto('/registro')
  await page.getByLabel('Nombre completo').fill('Cliente de prueba')
  await page.getByLabel('Correo electrónico').fill('cliente.e2e@example.com')
  await page.getByLabel('Contraseña', { exact: true }).fill('clientpass123')
  await page.getByLabel('Confirmar contraseña', { exact: true }).fill('differentpass')
  await page.getByRole('button', { name: 'Crear mi cuenta' }).click()
  await expect(page.getByText('Las contraseñas no coinciden.')).toBeVisible()
  await page.getByLabel('Confirmar contraseña', { exact: true }).fill('clientpass123')
  await page.getByRole('button', { name: 'Crear mi cuenta' }).click()
  await expect(page).toHaveURL(/\/mi-cuenta$/)
  await page.reload()
  await expect(page.getByLabel('Nombre completo')).toHaveValue('Cliente de prueba')
  await page.getByLabel('Nombre completo').fill('Cliente actualizado')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByText('Tus cambios se guardaron correctamente.')).toBeVisible()
  await page.getByLabel('Contraseña actual', { exact: true }).fill('clientpass123')
  await page.getByLabel('Nueva contraseña', { exact: true }).fill('newclientpass123')
  await page.getByLabel('Confirmar nueva contraseña', { exact: true }).fill('newclientpass123')
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByLabel('Nueva contraseña', { exact: true })).toHaveValue('')
  await page.goto('/admin/usuarios')
  await expect(page.getByRole('heading', { name: 'Este espacio es del equipo.' })).toBeVisible()
  expect((await page.request.get('/api/users', { headers: { Origin: 'http://127.0.0.1:4173', Accept: 'application/json' } })).status()).toBe(403)
  await page.getByRole('link', { name: 'Ir a mi perfil' }).click()
  await page.screenshot({ path: 'test-results/profile-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Correo electrónico').fill('cliente.e2e@example.com')
  await page.getByLabel('Contraseña', { exact: true }).fill('newclientpass123')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page).toHaveURL(/\/mi-cuenta$/)
})

test('admin login, create, edit, search, roles, deletion and self-protection', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('Correo electrónico').fill('admin@tienda.com')
  await page.getByLabel('Contraseña', { exact: true }).fill('wrongpassword')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByText('El correo o la contraseña no son correctos.')).toBeVisible()
  await page.getByLabel('Contraseña', { exact: true }).fill('password123')
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page).toHaveURL(/\/admin\/usuarios$/)
  await expect(page.getByRole('button', { name: 'Eliminar a Admin Tienda', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Crear usuario', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre completo').fill('Usuario temporal')
  await dialog.getByLabel('Correo electrónico').fill('temporal.e2e@example.com')
  await dialog.getByLabel('Contraseña', { exact: true }).fill('temporalpass123')
  await dialog.getByLabel('Confirmar contraseña', { exact: true }).fill('temporalpass123')
  await dialog.getByRole('button', { name: 'Crear usuario', exact: true }).click()
  await expect(page.getByText('Usuario creado.')).toBeVisible()
  await page.getByRole('button', { name: 'Editar a Usuario temporal' }).click()
  await dialog.getByLabel('Nombre completo').fill('Usuario editado')
  await dialog.getByLabel('Rol', { exact: true }).selectOption('admin')
  await dialog.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByText('Usuario actualizado.')).toBeVisible()
  await page.getByRole('searchbox').fill('temporal.e2e')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Usuario editado' })).toHaveCount(1)
  await page.getByLabel('Filtrar por rol').selectOption('cliente')
  await expect(page.getByText('No encontramos usuarios')).toBeVisible()
  await page.getByRole('button', { name: 'Limpiar filtros' }).click()
  await expect(page.getByRole('button', { name: 'Eliminar a Usuario editado' })).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/users-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: 'test-results/users-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Eliminar a Usuario editado' }).click()
  await dialog.getByRole('button', { name: 'Cancelar' }).click()
  await expect(page.getByRole('button', { name: 'Eliminar a Usuario editado' })).toBeVisible()
  await page.getByRole('button', { name: 'Eliminar a Usuario editado' }).click()
  await dialog.getByRole('button', { name: 'Eliminar cuenta' }).click()
  await expect(page.getByText('Usuario eliminado.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Eliminar a Usuario editado' })).toHaveCount(0)
})

test('CSRF rejects forged writes and missing cookies', async ({ request }) => {
  const response = await request.post('/api/register', {
    headers: { Origin: 'http://127.0.0.1:4173', Accept: 'application/json' },
    data: { name: 'Forged', email: 'forged@example.com', password: 'password123', password_confirmation: 'password123' },
  })
  expect(response.status()).toBe(419)
})
